  const done = [], missing = [];
  for (const [name, t] of Object.entries(MAP)) {
    const a = game.actors.find(x => inFolder(x) && x.name === name);
    if (!a) { missing.push(name); continue; }
    const tex = { "texture.src": BASE + t.file, "texture.scaleX": t.scale, "texture.scaleY": t.scale,
                  "texture.anchorX": t.anchorX, "texture.anchorY": t.anchorY,
                  "ring.enabled": false, "flags.pf2e.autoscale": false };
    const proto = {}; for (const [k, v] of Object.entries(tex)) proto["prototypeToken." + k] = v;
    await a.update({ img: a.img, ...proto });
    for (const sc of game.scenes) {
      const ups = sc.tokens.filter(tk => tk.actorId === a.id).map(tk => ({ _id: tk.id, ...tex }));
      if (ups.length) await sc.updateEmbeddedDocuments("Token", ups);
    }
    done.push(`${name} (x${t.scale})`);
  }
